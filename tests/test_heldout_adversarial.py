    def test_event_time_controls_exposure_and_order_when_arrival_time_disagrees(self):
        # The input is intentionally supplied out of event-time order. W2 was
        # recorded inside the window but processed after it; W1 is the reverse.
        rows = [
            step("W2", "S2", timestamp="2026-11-21T03:30:00+00:00", recorded_at="2026-11-21T02:00:00+00:00"),
            step("W3", "S4", timestamp="2026-11-21T04:00:00+00:00", recorded_at="2026-11-21T01:00:00+00:00"),
            step("W1", "S1", timestamp="2026-11-21T02:30:00+00:00", recorded_at="2026-11-21T08:00:00+00:00"),
            step("W3", "S3", timestamp="2026-11-21T01:00:00+00:00", recorded_at="2026-11-21T09:00:00+00:00"),
        ]
        data = investigation(rows, ["W1", "W2", "W3"])
        data["coverage"]["window_end"] = "2026-11-21T05:00:00+00:00"
        result = analyze(data)
        self.assertEqual(exposure(result)["definitely_exposed"], ["W1", "W3"])
        self.assertEqual(exposure(result)["not_observed_exposed"], [])
        self.assertEqual(exposure(result)["not_observed_exposed_under_unverified_coverage"], ["W2"])
        journey = next(item for item in result["transformations"][1]["journeys"] if item["wafer_id"] == "W3")
        self.assertEqual([item["step_instance_id"] for item in journey["steps"]], ["S3", "S4"])
        self.assertEqual(journey["steps"][0]["timestamp_utc"], "2026-11-21T01:00:00+00:00")
        self.assertEqual(journey["steps"][0]["recorded_at"], "2026-11-21T09:00:00+00:00")
        self.assertTrue(all(item["source_id"] == PROCESS_SOURCE["id"]
                            and item["relationship_id"] == PROCESS_RELATION["id"]
                            for item in journey["steps"]))

    def test_equally_supported_equipment_hypotheses_remain_unranked(self):
        rows = [
            step("W-T1-A", "S-T1-A", chamber="C1", tool="T1"),
            step("W-T1-N", "S-T1-N", chamber="C1", tool="T1"),
            step("W-T2-A", "S-T2-A", chamber="C2", tool="T2"),
            step("W-T2-N", "S-T2-N", chamber="C2", tool="T2"),
        ]
        members = ["W-T1-A", "W-T1-N", "W-T2-A", "W-T2-N"]
        data = investigation(rows, members)
        outcome_relation = copy.deepcopy(OUTCOME_RELATION)
        outcome_relation["keys"] = ["wafer_id", "timestamp", "label"]
        data["sources"].append(copy.deepcopy(OUTCOME_SOURCE))
        data["relationships"].append(outcome_relation)
        labels = {"W-T1-A": "ABNORMAL", "W-T1-N": "NORMAL", "W-T2-A": "ABNORMAL", "W-T2-N": "NORMAL"}
        data["outcomes"] = [{
            "wafer_id": wafer_id,
            "label": label,
            "timestamp": "2026-11-21T06:00:00+00:00",
            "source_id": OUTCOME_SOURCE["id"],
            "relationship_id": outcome_relation["id"],
            "approved_relationship": True,
        } for wafer_id, label in labels.items()]

        result = analyze(data)
        comparison = result["counterevidence"][0]
        hypotheses = comparison["confounders"]["equipment"]["alternative_equipment_hypotheses"]
        tools = {item["equipment_id"]: item for item in hypotheses if item["equipment_type"] == "TOOL"}
        self.assertEqual(set(tools), {"T1", "T2"})
        for tool_id, abnormal, normal, nonmatch_abnormal, nonmatch_normal in (
            ("T1", "W-T1-A", "W-T1-N", "W-T2-A", "W-T2-N"),
            ("T2", "W-T2-A", "W-T2-N", "W-T1-A", "W-T1-N"),
        ):
            hypothesis = tools[tool_id]
            self.assertEqual(hypothesis["abnormal_wafers_with_observed_exact_event"], [abnormal])
            self.assertEqual(hypothesis["normal_wafers_with_observed_exact_event"], [normal])
            self.assertEqual(hypothesis["abnormal_wafers_without_observed_exact_event"], [])
            self.assertEqual(hypothesis["normal_wafers_without_observed_exact_event"], [])
            self.assertEqual(hypothesis["abnormal_wafers_not_observed_under_unverified_coverage"], [nonmatch_abnormal])
            self.assertEqual(hypothesis["normal_wafers_not_observed_under_unverified_coverage"], [nonmatch_normal])
            self.assertEqual(hypothesis["coverage"]["accepted_for_nonmatch_classification"], False)
            self.assertNotIn("rank", hypothesis)
        self.assertEqual(comparison["statistical_association"]["status"], "NOT_COMPUTED")
        self.assertEqual(comparison["causal_conclusion"]["status"], "NOT_ESTABLISHED")

